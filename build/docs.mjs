/**
 * Generates docs/assets/nav.js from the <meta name="docs:*"> tags of every docs page.
 *   <title>Select</title>
 *   <meta name="docs:section" content="Pickers & Selects">
 *   <meta name="docs:order" content="10">
 *   <meta name="docs:desc" content="Searchable, multi-select dropdowns">
 */
import fs from 'node:fs';
import path from 'node:path';

export const SECTIONS = [
  'Getting Started', 'Foundation', 'Layout & Navigation', 'Overlays & Feedback', 'Forms', 'Pickers & Selects',
  'Data', 'Charts', 'Dashboard', 'Scheduling', 'Boards & Diagrams', 'Media', 'Uploads', 'Editors',
  'Devices & Capture', 'Communication', 'AI', 'Search & Commands', 'Auth & Onboarding', 'Maps',
  'Services & Utilities', 'Templates',
];

/** Decode the entities that legitimately appear in a title/description. The consumer
 *  (docs/assets/docs.js) re-escapes with escH(), so nav data is stored as plain text. */
const decode = s => s.replace(/&(lt|gt|quot|apos|#0?39|nbsp|amp);/gi, (_, e) => ({
  lt: '<', gt: '>', quot: '"', apos: "'", '#39': "'", '#039': "'", nbsp: ' ', amp: '&',
}[e.toLowerCase()]));
const meta = (html, name) => {
  const m = html.match(new RegExp(`<meta\\s+name=["']docs:${name}["']\\s+content=["']([^"']*)["']`, 'i'));
  return m ? decode(m[1]) : null;
};

export function buildDocsNav(root) {
  const docs = path.join(root, 'docs');
  const pages = [];
  const scan = (dir, prefix) => {
    if (!fs.existsSync(dir)) return;
    for (const f of fs.readdirSync(dir)) {
      if (!f.endsWith('.html')) continue;
      const html = fs.readFileSync(path.join(dir, f), 'utf8').slice(0, 4000);
      const section = meta(html, 'section');
      if (!section) continue;
      const raw = meta(html, 'title') || decode((html.match(/<title>([^<]*)<\/title>/i) || [])[1] || f);
      const title = raw.replace(/\s*[—|-]\s*Orion.*$/i, '').trim();
      pages.push({ href: prefix + f, title, section, order: +(meta(html, 'order') || 50), desc: meta(html, 'desc') || '' });
    }
  };
  scan(docs, '');
  scan(path.join(docs, 'components'), 'components/');
  scan(path.join(docs, 'templates'), 'templates/');
  const secIndex = s => { const i = SECTIONS.indexOf(s); return i < 0 ? 999 : i; };
  pages.sort((a, b) => secIndex(a.section) - secIndex(b.section) || a.section.localeCompare(b.section) || a.order - b.order || a.title.localeCompare(b.title));
  const nav = [];
  for (const p of pages) {
    let s = nav.find(x => x.section === p.section);
    if (!s) nav.push(s = { section: p.section, pages: [] });
    s.pages.push({ href: p.href, title: p.title, desc: p.desc });
  }
  const out = path.join(docs, 'assets', 'nav.js');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const tmp = out + '.' + process.pid + '.tmp';
  fs.writeFileSync(tmp, '/* generated by build/docs.mjs — do not edit */\nwindow.DOCS_NAV = ' + JSON.stringify(nav, null, 1) + ';\n');
  fs.renameSync(tmp, out);
  return nav;
}
